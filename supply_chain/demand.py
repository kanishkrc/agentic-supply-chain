"""
Demand generator — Merton Jump Diffusion model.

The paper (§5, Appendix 17) uses customer demand generated by a
Merton Jump Diffusion process (Liu et al. 2022, run #13).

Characteristics visible in Figure 17:
  - Starts at ~8-12 units, volatile for first ~25 steps
  - Large negative spike around step 20-30 drives demand to near 0
  - Stays low (~0-2) from step 30 onward
  - Occasional small bumps near steps 130 and 175
  - Always clipped to [0, 20]

Merton (1976) discrete update:
  S(t) = S(t-1) * exp((μ - σ²/2)·dt + σ·√dt·Z) + J_t
  where
    Z     ~ N(0,1)               Brownian increment
    N_t   ~ Poisson(λ·dt)        number of jumps this step
    J_t   = S(t-1) · Σ exp(N(μ_j, σ_j))   relative jump sizes
"""

import numpy as np
from typing import Tuple


def generate_demand(
    n_steps: int   = 200,
    S0: float      = 8.0,
    mu: float      = -0.015,
    sigma: float   = 0.25,
    lam: float     = 0.03,
    mu_j: float    = -4.0,
    sigma_j: float = 1.0,
    clip: Tuple[int, int] = (0, 20),
    seed: int      = 13,
    dt: float      = 1.0,
) -> np.ndarray:
    """
    Generate a demand sequence using the Merton Jump Diffusion model.

    Parameters
    ----------
    n_steps  : total simulation steps (paper uses 200)
    S0       : initial demand level
    mu       : GBM drift
    sigma    : GBM volatility
    lam      : Poisson jump intensity (expected jumps per step)
    mu_j     : mean jump magnitude (additive, applied to current level)
    sigma_j  : std dev of jump magnitude
    clip     : (min, max) demand clipping range (paper: 0–20)
    seed     : random seed — paper uses run #13 → seed=13
    dt       : time increment (1 step)

    Returns
    -------
    demands : np.ndarray of shape (n_steps,), dtype int
    """
    rng = np.random.default_rng(seed)

    S = np.zeros(n_steps, dtype=float)
    S[0] = S0

    for t in range(1, n_steps):
        # ── Diffusion component (Geometric Brownian Motion) ────────────────
        z          = rng.standard_normal()
        diffusion  = np.exp((mu - 0.5 * sigma ** 2) * dt + sigma * np.sqrt(dt) * z)

        # ── Jump component ─────────────────────────────────────────────────
        n_jumps = rng.poisson(lam * dt)
        if n_jumps > 0:
            # Each jump is additive (relative to current level)
            jump_sizes = rng.normal(mu_j, sigma_j, n_jumps)
            jump = np.sum(jump_sizes)
        else:
            jump = 0.0

        S[t] = S[t - 1] * diffusion + jump

    # Clip to valid demand range and round to integer units
    demands = np.clip(S, clip[0], clip[1])
    return np.round(demands).astype(int)


def get_paper_demand(config: dict | None = None) -> np.ndarray:
    """
    Convenience wrapper that reads parameters from a config dict
    and returns the demand sequence matching the paper's setup.

    Parameters
    ----------
    config : dict with demand_* keys (see supply_chain/config.py).
             Uses DEFAULT_CONFIG values if None.
    """
    from .config import DEFAULT_CONFIG
    cfg = config or DEFAULT_CONFIG

    return generate_demand(
        n_steps  = cfg["n_steps"],
        S0       = cfg["demand_S0"],
        mu       = cfg["demand_mu"],
        sigma    = cfg["demand_sigma"],
        lam      = cfg["demand_lam"],
        mu_j     = cfg["demand_mu_j"],
        sigma_j  = cfg["demand_sigma_j"],
        clip     = cfg["demand_clip"],
        seed     = cfg["demand_seed"],
    )
